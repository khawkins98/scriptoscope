#!/usr/bin/env node
// scripts/report-coverage.mjs
//
// Reports routine coverage against docs/spec/routine-inventory.json, the
// address-only denominator. This is a count of routines. It is NOT a fidelity
// percentage and must never be reported as one.
//
//   cited    : some docs/, src/ or ledger line names an address inside the routine.
//              Being cited does not mean the routine is decoded.
//   decoded  : an address inside the routine is cited by a behavioural engine spec,
//              docs/spec/engine/<family>.md (not TEMPLATE.md or IMPLEMENTER-BRIEF.md,
//              not *.evidence.md).
//   mirrored : src/engine/coverage.json maps an address range overlapping the routine
//              to a table row or driver. Entries marked 'out-of-scope' or
//              'unmirrored' don't count.
//
// Addresses are attributed to a binary by a namespace heuristic. A line that
// mentions PACH, a CDEF number or an Apple/1.8.2 source is attributed to that
// namespace. Otherwise the file decides: pach/header-surface paths count as
// PACH 130, cdef8/tab- paths as CDEF 8, and everything else as kDEF 0. This is
// the advisor's heuristic, so expect some misattribution.
//
// While the inventory status is PROVISIONAL, the in-scope count isn't frozen.
// The report shows the heuristic render-relevant count as a provisional
// reference, not as the in-scope denominator.
//
// Usage:
//   node scripts/report-coverage.mjs           # table on stdout
//   node scripts/report-coverage.mjs --json    # machine-readable

import { readFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import { resolve, dirname, relative, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const inv = JSON.parse(readFileSync(resolve(repoRoot, 'docs/spec/routine-inventory.json'), 'utf8'));
const col = Object.fromEntries(inv.columns.map((c, i) => [c, i]));
const renderRelevant = new Set(inv.renderRelevantClasses);

function walk(dir, out = []) {
  if (!existsSync(dir)) return out;
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (/\.(md|ts|mjs|js|json)$/.test(name)) out.push(p);
  }
  return out;
}

const NS_HINT = [
  ['PACH130', /PACH|pach130|patch/i],
  ['CDEF8', /CDEF ?8|cdef8|tab-cdef8/i],
  ['CDEF3', /CDEF ?3\b/], ['CDEF4', /CDEF ?4\b/], ['CDEF5', /CDEF ?5\b/],
  ['CDEF6', /CDEF ?6\b/], ['CDEF7', /CDEF ?7\b/], ['CDEF1019', /CDEF ?1019\b/],
  ['apple', /Apple|AppearanceLib|WDEF ?125|CDEF ?-|Platinum Engine|PPC|PowerPC|capstone|1\.8\.2|k182/i],
];
const ADDR = /0x([0-9a-fA-F]{3,6})\b/g;
const SELF = 'docs/spec/routine-inventory.json';

/** ns -> Set(addr) for the given files. */
function citations(files) {
  const out = new Map();
  for (const f of files) {
    const rel = relative(repoRoot, f);
    if (rel === SELF || rel.startsWith('docs/v2/')) continue; // plans name ranges to decode; they are not citations
    let fdefault = /pach/i.test(rel) || rel.includes('header-surface') ? 'PACH130'
      : rel.includes('cdef8') || rel.includes('tab-') ? 'CDEF8' : 'kDEF0';
    if (/apple|platinum-(wdef|controls|theme)|kdef182/.test(rel)) fdefault = 'apple';
    for (const line of readFileSync(f, 'utf8').split('\n')) {
      const ns = NS_HINT.find(([, rx]) => rx.test(line))?.[0] ?? fdefault;
      for (const m of line.matchAll(ADDR)) {
        if (!out.has(ns)) out.set(ns, new Set());
        out.get(ns).add(parseInt(m[1], 16));
      }
    }
  }
  return out;
}

const citedFiles = [
  ...walk(resolve(repoRoot, 'docs')), ...walk(resolve(repoRoot, 'src')),
  ...walk(resolve(repoRoot, 'tests/rendering-requirements')), resolve(repoRoot, 'LEARNINGS.md'),
].filter(existsSync);
const engineSpecs = walk(resolve(repoRoot, 'docs/spec/engine'))
  .filter((f) => f.endsWith('.md') && !f.endsWith('.evidence.md') && !/\/(TEMPLATE|IMPLEMENTER-BRIEF)\.md$/.test(f));
const cited = citations(citedFiles);
const decoded = citations(engineSpecs);

// src/engine/coverage.json (generated by the engine; may not exist yet).
// Accepted shape: { "<binary>": [ { "range": ["0x..", "0x.."], "kind": "row"|"driver"|"out-of-scope"|"unmirrored" } ] }
const covPath = resolve(repoRoot, 'src/engine/coverage.json');
const mirrored = new Map();
if (existsSync(covPath)) {
  const cov = JSON.parse(readFileSync(covPath, 'utf8'));
  for (const [bin, entries] of Object.entries(cov)) {
    if (!Array.isArray(entries)) continue;
    mirrored.set(bin, entries.filter((e) => e.kind === 'row' || e.kind === 'driver')
      .map((e) => e.range.map((x) => parseInt(x, 16))));
  }
}

const inRange = (set, s, e) => { if (!set) return false; for (const a of set) if (a >= s && a < e) return true; return false; };
const report = { status: inv.status, inScopeFrozen: inv.inScope?.frozen === true, inScopeCount: inv.inScope?.count ?? null, binaries: {} };
const total = { routines: 0, renderRelevant: 0, cited: 0, decoded: 0, mirrored: 0, citedRR: 0, decodedRR: 0, mirroredRR: 0 };
for (const [name, b] of Object.entries(inv.binaries)) {
  const r = { routines: 0, renderRelevant: 0, cited: 0, decoded: 0, mirrored: 0, citedRR: 0, decodedRR: 0, mirroredRR: 0 };
  for (const row of b.routines) {
    const s = parseInt(row[col.start], 16), e = parseInt(row[col.end], 16);
    const rr = renderRelevant.has(row[col.class]);
    const c = inRange(cited.get(name), s, e);
    const d = inRange(decoded.get(name), s, e);
    const m = (mirrored.get(name) ?? []).some(([ms, me]) => ms < e && me > s);
    r.routines++; if (rr) r.renderRelevant++;
    if (c) { r.cited++; if (rr) r.citedRR++; }
    if (d) { r.decoded++; if (rr) r.decodedRR++; }
    if (m) { r.mirrored++; if (rr) r.mirroredRR++; }
  }
  report.binaries[name] = r;
  for (const k of Object.keys(total)) total[k] += r[k];
}
report.total = total;

if (process.argv.includes('--json')) {
  console.log(JSON.stringify(report, null, 2));
} else {
  const pad = (v, n) => String(v).padStart(n);
  console.log(`routine coverage (inventory status: ${inv.status}; in-scope ${report.inScopeFrozen ? 'frozen at ' + report.inScopeCount : 'NOT frozen'})`);
  console.log('counts of routines, not a fidelity percentage; RR = heuristic render-relevant (provisional)');
  console.log('binary     routines   RR   cited(RR)  decoded(RR)  mirrored(RR)');
  for (const [n, r] of [...Object.entries(report.binaries), ['total', total]]) {
    console.log(`${n.padEnd(9)} ${pad(r.routines, 9)} ${pad(r.renderRelevant, 4)} ${pad(`${r.cited}(${r.citedRR})`, 10)} ${pad(`${r.decoded}(${r.decodedRR})`, 12)} ${pad(`${r.mirrored}(${r.mirroredRR})`, 13)}`);
  }
}
