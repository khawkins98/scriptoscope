// Kingfisher controls drawn with claude-pxl.
pal({ B: "#0f6a83", F: "#1689a8", W: "#ffffff", E: "#8d98a8", G: "#e2e7ee", S: "#4a5566", L: "#eef0f3", l: "#d0d4da" });

const box = (fill, edge) => (c) => {
  c.rect(0, 0, 14, 14, fill);
  c.box(0, 0, 14, 14, edge);
  for (const [x, y] of [[0,0],[1,0],[0,1],[13,0],[12,0],[13,1],[0,13],[1,13],[0,12],[13,13],[12,13],[13,12]]) c.px(x, y, "_");
  for (const [x, y] of [[1,1],[12,1],[1,12],[12,12]]) c.px(x, y, edge);
};
sprite("checkbox_off", { w: 14, h: 14 }, box("W", "E"));
sprite("checkbox_on", { w: 14, h: 14 }, box("F", "B"), `
..............
..............
..............
..........W...
.........WW...
...W....WW....
...WW..WW.....
....WWWW......
.....WW.......
..............
`);
sprite("checkbox_mixed", { w: 14, h: 14 }, box("F", "B"), (c) => c.rect(4, 6, 6, 2, "W"));
sprite("radio_off", { w: 14, h: 14 }, (c) => { c.circ(6.5, 6.5, 6.5, "W"); c.ring(6.5, 6.5, 6.5, "E"); });
sprite("radio_on", { w: 14, h: 14 }, (c) => { c.circ(6.5, 6.5, 6.5, "F"); c.ring(6.5, 6.5, 6.5, "B"); c.circ(6.5, 6.5, 2, "W"); });
sprite("close_button", { w: 12, h: 12 }, (c) => {
  c.circ(5.5, 5.5, 5.5, "F"); c.ring(5.5, 5.5, 5.5, "B");
  c.line(4, 4, 7, 7, "W"); c.line(7, 4, 4, 7, "W");
});
sheet("kingfisher", ["checkbox_*", "radio_*", "close_button"], { cols: 6, pad: 2 });
